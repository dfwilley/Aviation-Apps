#!/usr/bin/env python3
"""Turn HangarBoard/web/* into web_assets.h so the board can serve them.
mdb.js.gz is the mdb-reader library (MIT) bundled for browsers with tools/mdb-entry.js and esbuild."""
import os
here = os.path.dirname(os.path.abspath(__file__)); web = os.path.join(here, '..', 'HangarBoard', 'web')
def raw(name, path):
    s = open(path, encoding='utf-8').read(); assert ')WEB"' not in s
    return f'static const char {name}[] PROGMEM = R"WEB({s})WEB";\n'
gz = open(os.path.join(web, 'mdb.js.gz'), 'rb').read()
body = ',\n'.join(','.join(str(b) for b in gz[i:i+40]) for i in range(0, len(gz), 40))
out = ['// Generated by tools/embed.py from HangarBoard/web/ — edit those files, not this one.\n#pragma once\n#include <Arduino.h>\n',
       raw('SETTINGS_HTML', os.path.join(web, 'settings.html')), raw('DBIMPORT_JS', os.path.join(web, 'dbimport.js')),
       f'static const uint8_t MDB_JS_GZ[] PROGMEM = {{\n{body}\n}};\nstatic const size_t MDB_JS_GZ_LEN = {len(gz)};\n']
open(os.path.join(web, '..', 'web_assets.h'), 'w').write(''.join(out)); print('web_assets.h written,', len(gz), 'bytes gz')
